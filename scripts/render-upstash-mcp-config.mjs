#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, realpathSync } from "node:fs";
import { dirname, isAbsolute, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, "..");

export const UPSTASH_MCP_LAUNCHER_SHA256 =
  "651e4a9194348728f492274e9346172a3bbd51039883480e46c196cbb33f3a1f";

function assertLauncherInputs({ launcherPath, launcherSha256 }) {
  if (!isAbsolute(launcherPath)) {
    throw new Error("the Upstash launcher path must be absolute");
  }
  if (!/^[0-9a-f]{64}$/.test(launcherSha256)) {
    throw new Error("the Upstash launcher SHA-256 must be lowercase hex");
  }
}

export function buildLauncherVerifier({
  launcherPath,
  launcherSha256,
  runtimePath,
}) {
  assertLauncherInputs({ launcherPath, launcherSha256 });
  if (!isAbsolute(runtimePath)) {
    throw new Error("the personal Upstash MCP runtime path must be absolute");
  }

  return [
    'import { createHash } from "node:crypto";',
    'import { readFileSync } from "node:fs";',
    `const launcherPath = ${JSON.stringify(launcherPath)};`,
    `const expectedSha256 = ${JSON.stringify(launcherSha256)};`,
    `const runtimePath = ${JSON.stringify(runtimePath)};`,
    "const launcherBytes = readFileSync(launcherPath);",
    'const actualSha256 = createHash("sha256").update(launcherBytes).digest("hex");',
    "if (actualSha256 !== expectedSha256) {",
    '  throw new Error("Refusing to start Upstash MCP: launcher does not match the reviewed artifact");',
    "}",
    'const launcherUrl = `data:text/javascript;base64,${launcherBytes.toString("base64")}`;',
    "const { launchUpstashMcp } = await import(launcherUrl);",
    "await launchUpstashMcp({ runtimePath });",
  ].join("\n");
}

export function verifyUpstashMcpLauncher({
  launcherPath,
  expectedSha256 = UPSTASH_MCP_LAUNCHER_SHA256,
}) {
  assertLauncherInputs({ launcherPath, launcherSha256: expectedSha256 });
  const actualSha256 = createHash("sha256")
    .update(readFileSync(launcherPath))
    .digest("hex");
  if (actualSha256 !== expectedSha256) {
    throw new Error(
      "the Upstash MCP launcher does not match the reviewed artifact",
    );
  }
  return actualSha256;
}

export function renderUpstashMcpConfig({
  nodePath,
  launcherPath,
  runtimePath,
  launcherSha256 = UPSTASH_MCP_LAUNCHER_SHA256,
}) {
  if (!isAbsolute(nodePath)) {
    throw new Error("the Node path must be absolute");
  }
  const verifier = buildLauncherVerifier({
    launcherPath,
    launcherSha256,
    runtimePath,
  });

  return `# Personal, local-only config generated by the monitoring monorepo.
[mcp_servers.upstash]
args = ${JSON.stringify(["--input-type=module", "--eval", verifier])}
command = ${JSON.stringify(nodePath)}
default_tools_approval_mode = "prompt"
enabled = false
enabled_tools = [
  "redis_database_list_databases",
  "redis_database_run_redis_commands",
]
env_vars = ["UPSTASH_EMAIL", "UPSTASH_API_KEY"]
startup_timeout_sec = 40

[mcp_servers.upstash.tools.redis_database_run_redis_commands]
approval_mode = "prompt"
`;
}

export async function renderLocalUpstashMcpConfig({
  repoRoot = ROOT,
  runtimeDirectory,
} = {}) {
  const launcherPath = realpathSync(
    resolve(repoRoot, "scripts/upstash-mcp-launcher.mjs"),
  );
  verifyUpstashMcpLauncher({ launcherPath });
  const { prepareUpstashMcpRuntime } =
    await import("./build-upstash-mcp-runtime.mjs");
  const runtimePath = await prepareUpstashMcpRuntime({
    repoRoot,
    runtimeDirectory,
  });
  return renderUpstashMcpConfig({
    launcherPath,
    nodePath: realpathSync(process.execPath),
    runtimePath,
  });
}

function reviewedSnapshotRepoRoot(args) {
  if (args.length !== 2 || args[0] !== "--repo-root") {
    throw new Error(
      "usage: render-upstash-mcp-config.mjs --repo-root <absolute-checkout>",
    );
  }
  if (!isAbsolute(args[1])) {
    throw new Error("the Upstash MCP repository root must be absolute");
  }
  const repoRoot = realpathSync(args[1]);
  const checkoutScripts = realpathSync(resolve(repoRoot, "scripts"));
  if (realpathSync(SCRIPT_DIR) === checkoutScripts) {
    throw new Error(
      "run the config generator from an immutable reviewed commit snapshot",
    );
  }
  return repoRoot;
}

function isDirectInvocation(moduleUrl, argvPath) {
  if (!argvPath) return false;
  try {
    return (
      realpathSync(fileURLToPath(moduleUrl)) === realpathSync(resolve(argvPath))
    );
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

if (isDirectInvocation(import.meta.url, process.argv[1])) {
  Promise.resolve()
    .then(() => reviewedSnapshotRepoRoot(process.argv.slice(2)))
    .then((repoRoot) => renderLocalUpstashMcpConfig({ repoRoot }))
    .then((config) => process.stdout.write(config))
    .catch((error) => {
      console.error(`Refusing to configure Upstash MCP: ${error.message}`);
      process.exitCode = 1;
    });
}
