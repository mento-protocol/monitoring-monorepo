#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, realpathSync } from "node:fs";
import { dirname, isAbsolute, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));

export const UPSTASH_MCP_LAUNCHER_SHA256 =
  "44b23e61ca9775b2b319bd018099ccdef472ca809a7486b2e417b18e765d0b3b";

function assertLauncherInputs({ launcherPath, launcherSha256 }) {
  if (!isAbsolute(launcherPath)) {
    throw new Error("the Upstash launcher path must be absolute");
  }
  if (!/^[0-9a-f]{64}$/.test(launcherSha256)) {
    throw new Error("the Upstash launcher SHA-256 must be lowercase hex");
  }
}

export function buildLauncherVerifier({ launcherPath, launcherSha256 }) {
  assertLauncherInputs({ launcherPath, launcherSha256 });

  return [
    'import { createHash } from "node:crypto";',
    'import { readFileSync } from "node:fs";',
    'import { dirname } from "node:path";',
    `const launcherPath = ${JSON.stringify(launcherPath)};`,
    `const expectedSha256 = ${JSON.stringify(launcherSha256)};`,
    "const launcherBytes = readFileSync(launcherPath);",
    'const actualSha256 = createHash("sha256").update(launcherBytes).digest("hex");',
    "if (actualSha256 !== expectedSha256) {",
    '  throw new Error("Refusing to start Upstash MCP: launcher does not match the reviewed artifact");',
    "}",
    "const repoRoot = dirname(dirname(launcherPath));",
    'const launcherUrl = `data:text/javascript;base64,${launcherBytes.toString("base64")}`;',
    "const { launchUpstashMcp } = await import(launcherUrl);",
    "await launchUpstashMcp({ repoRoot });",
  ].join("\n");
}

export function verifyUpstashMcpLauncher({
  launcherPath,
  expectedSha256 = UPSTASH_MCP_LAUNCHER_SHA256,
}) {
  assertLauncherInputs({ launcherPath, launcherSha256: expectedSha256 });
  const actualSha256 = createHash("sha256")
    .update(readFileSync(launcherPath))
    .digest("hex");
  if (actualSha256 !== expectedSha256) {
    throw new Error(
      "the Upstash MCP launcher does not match the reviewed artifact",
    );
  }
  return actualSha256;
}

export function renderUpstashMcpConfig({
  nodePath,
  launcherPath,
  launcherSha256 = UPSTASH_MCP_LAUNCHER_SHA256,
}) {
  if (!isAbsolute(nodePath)) {
    throw new Error("the Node path must be absolute");
  }
  const verifier = buildLauncherVerifier({ launcherPath, launcherSha256 });

  return `# Personal, local-only config generated by the monitoring monorepo.
[mcp_servers.upstash]
args = ${JSON.stringify(["--input-type=module", "--eval", verifier])}
command = ${JSON.stringify(nodePath)}
default_tools_approval_mode = "prompt"
enabled = false
enabled_tools = [
  "redis_database_list_databases",
  "redis_database_run_redis_commands",
]
env_vars = ["UPSTASH_EMAIL", "UPSTASH_API_KEY"]
startup_timeout_sec = 40

[mcp_servers.upstash.tools.redis_database_run_redis_commands]
approval_mode = "prompt"
`;
}

export function renderLocalUpstashMcpConfig() {
  const launcherPath = realpathSync(
    resolve(SCRIPT_DIR, "upstash-mcp-launcher.mjs"),
  );
  verifyUpstashMcpLauncher({ launcherPath });
  return renderUpstashMcpConfig({
    launcherPath,
    nodePath: realpathSync(process.execPath),
  });
}

const invokedPath = process.argv[1]
  ? pathToFileURL(resolve(process.argv[1])).href
  : "";
if (import.meta.url === invokedPath) {
  process.stdout.write(renderLocalUpstashMcpConfig());
}
